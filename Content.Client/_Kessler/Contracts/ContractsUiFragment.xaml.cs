using Content.Shared._Kessler.Contracts;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Kessler.Contracts;

[GenerateTypedNameReferences]
public sealed partial class ContractsUiFragment : BoxContainer
{
    public event Action? OnRefresh;
    public event Action<NetEntity, int>? OnAccept;
    public event Action<NetEntity, int>? OnAbandon;

    public ContractsUiFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        Hint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("kessler-contracts-hint")));
    }

    public void UpdateState(ContractsUiState state)
    {
        ContractList.RemoveAllChildren();

        if (state.Problem != null)
            ContractList.AddChild(Wrapped(Loc.GetString(state.Problem), Color.IndianRed));

        AddHeader(Loc.GetString("kessler-contracts-held-header", ("count", state.Held.Count), ("max", state.MaxHeld)));
        if (state.Held.Count == 0)
            AddNote(Loc.GetString("kessler-contracts-none-held"));
        foreach (var entry in state.Held)
        {
            AddEntry(entry,
                Loc.GetString("kessler-contracts-entry-progress",
                    ("delivered", entry.Delivered), ("amount", entry.Amount), ("item", entry.Item), ("station", entry.StationName)),
                Loc.GetString("kessler-contracts-time-held", ("minutes", (int) entry.Remaining.TotalMinutes)),
                Loc.GetString("kessler-contracts-abandon"),
                () => OnAbandon?.Invoke(entry.Station, entry.Id),
                disabled: false);
        }

        AddHeader(Loc.GetString("kessler-contracts-open-header"));
        if (state.Open.Count == 0)
            AddNote(Loc.GetString("kessler-contracts-none-open"));
        var full = state.Held.Count >= state.MaxHeld || state.Problem != null;
        foreach (var entry in state.Open)
        {
            AddEntry(entry,
                Loc.GetString("kessler-contracts-entry", ("amount", entry.Amount), ("item", entry.Item), ("station", entry.StationName)),
                Loc.GetString("kessler-contracts-time-open",
                    ("hours", entry.TimeToDeliver.TotalHours.ToString("0.#")), ("minutes", (int) entry.Remaining.TotalMinutes)),
                Loc.GetString("kessler-contracts-accept"),
                () => OnAccept?.Invoke(entry.Station, entry.Id),
                disabled: full);
        }
    }

    private void AddHeader(string text)
    {
        ContractList.AddChild(new Label { Text = text, StyleClasses = { "LabelHeading" }, Margin = new Thickness(0, 8, 0, 2) });
    }

    private void AddNote(string text)
    {
        var note = Wrapped(text, Color.Gray);
        note.Margin = new Thickness(8, 0, 0, 0);
        ContractList.AddChild(note);
    }

    private void AddEntry(ContractEntry entry, string title, string time, string buttonText, Action onPressed, bool disabled)
    {
        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true, Margin = new Thickness(8, 2, 0, 4) };
        var text = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true };
        text.AddChild(Wrapped(title, null));
        text.AddChild(Wrapped(Loc.GetString("kessler-contracts-reward", ("reward", entry.Reward), ("rep", entry.Reputation), ("track", entry.Track)),
            Color.LightGreen));
        text.AddChild(Wrapped(time, Color.Gray));
        row.AddChild(text);

        var button = new Button { Text = buttonText, Disabled = disabled, VerticalAlignment = VAlignment.Center };
        button.OnPressed += _ => onPressed();
        row.AddChild(button);
        ContractList.AddChild(row);
    }

    /// <summary>
    /// Plain text that wraps to the PDA's width instead of running off the edge.
    /// </summary>
    private static RichTextLabel Wrapped(string text, Color? color)
    {
        var message = new FormattedMessage();
        if (color is { } c)
            message.PushColor(c);
        message.AddText(text);
        if (color != null)
            message.Pop();

        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(message);
        return label;
    }
}
