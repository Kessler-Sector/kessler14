using Content.Client.UserInterface.Controls;
using Content.Shared._Kessler.Licences;
using Content.Shared._NF.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Kessler.Licences;

/// <summary>
/// The licensing office: your reputation with each group, and every licence with what it allows, what it costs and
/// what you still need for it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LicenceOfficeMenu : FancyWindow
{
    private static readonly Color CardBackground = Color.FromHex("#1e1f24");
    private static readonly Color CardBorder = Color.FromHex("#3b3e47");
    private static readonly Color HeldColor = Color.FromHex("#7fd17f");
    private static readonly Color ReadyColor = Color.FromHex("#e0c060");
    private static readonly Color LockedColor = Color.FromHex("#d07070");
    private static readonly Color SubtleColor = Color.FromHex("#a0a4ad");

    public event Action<string>? OnBuy;

    public LicenceOfficeMenu()
    {
        RobustXamlLoader.Load(this);
        Hint.SetMessage(Colored(Loc.GetString("kessler-licence-office-hint"), SubtleColor));
        CharacterLabel.Text = Loc.GetString("kessler-licence-office-loading");
    }

    public void UpdateState(LicenceOfficeStateMessage state)
    {
        SectionList.RemoveAllChildren();

        NoticeLabel.Visible = state.Notice != null;
        if (state.Notice != null)
            NoticeLabel.SetMessage(Colored(state.Notice, ReadyColor));

        if (state.Problem != null)
        {
            CharacterLabel.Text = Loc.GetString("kessler-licence-office-title");
            SectionList.AddChild(Wrapped(Colored(state.Problem, LockedColor)));
            return;
        }

        CharacterLabel.Text = Loc.GetString("kessler-licence-office-character", ("name", state.CharacterName ?? string.Empty));

        AddHeading(Loc.GetString("kessler-licence-office-licences"));
        foreach (var licence in state.Licences)
        {
            SectionList.AddChild(MakeLicenceCard(licence));
        }

        AddHeading(Loc.GetString("kessler-licence-office-reputation"));
        foreach (var track in state.Tracks)
        {
            SectionList.AddChild(MakeTrackRow(track));
        }
    }

    private void AddHeading(string text)
    {
        SectionList.AddChild(new Label { Text = text, StyleClasses = { "LabelHeading" }, Margin = new Thickness(0, 8, 0, 4) });
    }

    private Control MakeLicenceCard(LicenceOfficeLicence licence)
    {
        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        var title = new RichTextLabel { HorizontalExpand = true };
        title.SetMessage(FormattedMessage.FromMarkupPermissive($"[bold]{FormattedMessage.EscapeText(licence.Name)}[/bold]"));
        header.AddChild(title);

        if (licence.HeldSince is { } since)
        {
            header.AddChild(new Label
            {
                Text = Loc.GetString("kessler-licence-office-held", ("date", since.ToString("yyyy-MM-dd"))),
                FontColorOverride = HeldColor,
            });
        }
        else
        {
            var buy = new Button
            {
                Text = Loc.GetString("kessler-licence-office-buy", ("fee", BankSystemExtensions.ToSpesoString(licence.Fee))),
                Disabled = licence.Missing.Count > 0,
                VerticalAlignment = VAlignment.Top,
            };
            var id = licence.Id;
            buy.OnPressed += _ => OnBuy?.Invoke(id);
            header.AddChild(buy);
        }

        body.AddChild(header);

        if (licence.Description.Length > 0)
            body.AddChild(Wrapped(Colored(licence.Description, SubtleColor)));

        if (licence.HeldSince == null)
        {
            if (licence.Missing.Count == 0)
            {
                body.AddChild(Wrapped(Colored(Loc.GetString("kessler-licence-office-ready"), ReadyColor)));
            }
            else
            {
                var needs = new FormattedMessage();
                needs.PushColor(LockedColor);
                needs.AddText(Loc.GetString("kessler-licence-office-needs"));
                foreach (var line in licence.Missing)
                {
                    needs.PushNewline();
                    needs.AddText("• " + line);
                }

                needs.Pop();
                body.AddChild(Wrapped(needs));
            }
        }

        return Card(body);
    }

    private static Control MakeTrackRow(LicenceOfficeTrack track)
    {
        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, Margin = new Thickness(0, 0, 0, 6) };

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        header.AddChild(new Label { Text = track.Name, HorizontalExpand = true });
        header.AddChild(new Label
        {
            Text = track.NextLevel is { } next
                ? Loc.GetString("kessler-licence-office-track-progress", ("level", track.LevelName), ("points", track.Points), ("next", next))
                : Loc.GetString("kessler-licence-office-track-max", ("level", track.LevelName), ("points", track.Points)),
            FontColorOverride = SubtleColor,
        });
        body.AddChild(header);

        var span = (track.NextLevel ?? track.Points) - track.LevelStart;
        body.AddChild(new ProgressBar
        {
            MinValue = 0,
            MaxValue = Math.Max(1, span),
            Value = track.NextLevel == null ? Math.Max(1, span) : track.Points - track.LevelStart,
            MinHeight = 8,
            HorizontalExpand = true,
            Margin = new Thickness(0, 2, 0, 2),
        });

        if (track.Description.Length > 0)
            body.AddChild(Wrapped(Colored(track.Description, SubtleColor)));

        return body;
    }

    private static PanelContainer Card(Control content)
    {
        var card = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 8),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = CardBackground,
                BorderColor = CardBorder,
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 10,
                ContentMarginTopOverride = 8,
                ContentMarginBottomOverride = 8,
            },
        };
        card.AddChild(content);
        return card;
    }

    private static FormattedMessage Colored(string text, Color color)
    {
        var message = new FormattedMessage();
        message.PushColor(color);
        message.AddText(text);
        message.Pop();
        return message;
    }

    private static RichTextLabel Wrapped(FormattedMessage message)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(message);
        return label;
    }
}
