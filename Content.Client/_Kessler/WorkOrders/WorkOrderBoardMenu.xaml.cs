using Content.Client.UserInterface.Controls;
using Content.Shared._Kessler.WorkOrders;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Kessler.WorkOrders;

[GenerateTypedNameReferences]
public sealed partial class WorkOrderBoardMenu : FancyWindow
{
    public WorkOrderBoardMenu()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(WorkOrderBoardUiState state)
    {
        OrdersList.RemoveAllChildren();
        EmptyLabel.Visible = state.Orders.Count == 0;

        foreach (var order in state.Orders)
        {
            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(4, 4, 4, 8),
            };

            var title = new RichTextLabel();
            title.SetMessage(Loc.GetString("kessler-work-order-entry-title", ("title", order.Title)));
            box.AddChild(title);

            box.AddChild(new Label
            {
                Text = order.Description,
                StyleClasses = { "LabelSubText" },
            });

            var details = Loc.GetString("kessler-work-order-entry-details",
                ("payout", order.Payout),
                ("reputation", order.Reputation),
                ("track", order.Track),
                ("minutes", order.MinutesLeft));
            if (order.Total > 0)
                details += " " + Loc.GetString("kessler-work-order-entry-progress", ("remaining", order.Remaining), ("total", order.Total));

            box.AddChild(new Label { Text = details });
            OrdersList.AddChild(box);
        }
    }
}
