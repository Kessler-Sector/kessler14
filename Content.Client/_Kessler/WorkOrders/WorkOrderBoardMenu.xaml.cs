using Content.Client.UserInterface.Controls;
using Content.Shared._Kessler.WorkOrders;
using Content.Shared._NF.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Kessler.WorkOrders;

/// <summary>
/// The work-order board: one card per open order with what to do, what it pays, where the work is and how long is
/// left.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WorkOrderBoardMenu : FancyWindow
{
    private static readonly Color CardBackground = Color.FromHex("#1e1f24");
    private static readonly Color CardBorder = Color.FromHex("#3b3e47");
    private static readonly Color PayColor = Color.FromHex("#7fd17f");
    private static readonly Color SubtleColor = Color.FromHex("#a0a4ad");

    public WorkOrderBoardMenu()
    {
        RobustXamlLoader.Load(this);
        Hint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("kessler-work-order-board-hint")));
    }

    public void UpdateState(WorkOrderBoardUiState state)
    {
        OrdersList.RemoveAllChildren();
        EmptyLabel.Visible = state.Orders.Count == 0;

        foreach (var order in state.Orders)
        {
            OrdersList.AddChild(MakeCard(order));
        }
    }

    private static Control MakeCard(WorkOrderBoardEntry order)
    {
        var card = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 8),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = CardBackground,
                BorderColor = CardBorder,
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 10,
                ContentMarginTopOverride = 8,
                ContentMarginBottomOverride = 8,
            },
        };

        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        card.AddChild(body);

        // Title on the left, pay on the right.
        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        var title = new RichTextLabel { HorizontalExpand = true };
        title.SetMessage(FormattedMessage.FromMarkupPermissive(
            Loc.GetString("kessler-work-order-entry-title", ("title", FormattedMessage.EscapeText(order.Title)))));
        header.AddChild(title);
        header.AddChild(new Label
        {
            Text = BankSystemExtensions.ToSpesoString(order.Payout),
            FontColorOverride = PayColor,
            VerticalAlignment = VAlignment.Top,
            Margin = new Thickness(8, 0, 0, 0),
        });
        body.AddChild(header);

        body.AddChild(Text(FormattedMessage.FromUnformatted(order.Description), SubtleColor, new Thickness(0, 4, 0, 0)));

        if (order.Spots.Count > 0)
        {
            var where = new FormattedMessage();
            where.AddMarkupPermissive(Loc.GetString("kessler-work-order-entry-where",
                ("remaining", order.Remaining), ("total", order.Total)));
            foreach (var spot in order.Spots)
            {
                where.PushNewline();
                where.AddMarkupPermissive(Loc.GetString("kessler-work-order-entry-spot", ("location", spot)));
            }

            body.AddChild(Text(where, null, new Thickness(0, 6, 0, 0)));
        }

        body.AddChild(Text(FormattedMessage.FromUnformatted(Loc.GetString("kessler-work-order-entry-footer",
                ("reputation", order.Reputation),
                ("track", order.Track),
                ("minutes", order.MinutesLeft))),
            SubtleColor,
            new Thickness(0, 6, 0, 0)));

        return card;
    }

    private static RichTextLabel Text(FormattedMessage message, Color? color, Thickness margin)
    {
        var label = new RichTextLabel { HorizontalExpand = true, Margin = margin };
        if (color is { } c)
        {
            var colored = new FormattedMessage();
            colored.PushColor(c);
            colored.AddMessage(message);
            colored.Pop();
            message = colored;
        }

        label.SetMessage(message);
        return label;
    }
}
