using Content.Shared._Kessler.Market;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Kessler.Market;

[GenerateTypedNameReferences]
public sealed partial class MarketBoardUiFragment : BoxContainer
{
    public event Action? OnRefresh;

    public MarketBoardUiFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
    }

    public void UpdateState(MarketBoardUiState state)
    {
        StationList.RemoveAllChildren();

        if (state.Stations.Count == 0)
        {
            StationList.AddChild(new Label { Text = Loc.GetString("kessler-market-board-empty") });
            return;
        }

        foreach (var station in state.Stations)
        {
            var name = station.Market == state.Here
                ? Loc.GetString("kessler-market-board-here", ("station", station.Name))
                : station.Name;
            StationList.AddChild(new Label { Text = name, StyleClasses = { "LabelHeading" }, Margin = new Thickness(0, 6, 0, 2) });

            foreach (var rate in station.Rates)
            {
                var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
                row.AddChild(new Label { Text = rate.Category, HorizontalExpand = true, Margin = new Thickness(8, 0, 0, 0) });
                row.AddChild(new Label
                {
                    Text = $"{rate.Percent}%",
                    FontColorOverride = rate.Percent >= 100 ? Color.LightGreen : rate.Percent >= 70 ? Color.Yellow : Color.IndianRed,
                });
                StationList.AddChild(row);
            }

            if (station.Needs.Count == 0)
                continue;

            StationList.AddChild(new Label { Text = Loc.GetString("kessler-market-board-stocks"), FontColorOverride = Color.Gray, Margin = new Thickness(8, 2, 0, 0) });
            foreach (var need in station.Needs)
            {
                var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
                row.AddChild(new Label { Text = need.Category, HorizontalExpand = true, Margin = new Thickness(16, 0, 0, 0) });
                row.AddChild(new Label
                {
                    Text = $"{need.Percent}%",
                    FontColorOverride = need.Percent >= 50 ? Color.LightGreen : need.Percent >= 25 ? Color.Yellow : Color.IndianRed,
                });
                StationList.AddChild(row);
            }
        }
    }
}
